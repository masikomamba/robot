"""Generate room_hall.sdf (kept out of the package, output is committed)."""
FT = 0.3048
T = 0.10          # wall thickness (m)
HGT = 0.60        # wall height (m)
L, W, H = 15 * FT, 10 * FT, 5 * FT   # room length, room width, hall width
D = 5 * FT        # doorway width

walls = []  # (name, xmin, xmax, ymin, ymax, color)
ROOM = '0.80 0.65 0.45 1'
HALL = '0.45 0.60 0.80 1'
# Room walls
walls.append(('room_north_wall', -T, L + 2 * T + H, W, W + T, ROOM))
walls.append(('room_west_wall', -T, 0.0, -2 * T - H, W, ROOM))
walls.append(('room_south_wall_left', 0.0, 5 * FT, -T, 0.0, ROOM))
walls.append(('room_south_wall_right', 10 * FT, L + T, -T, 0.0, ROOM))
walls.append(('room_east_wall', L, L + T, -T, W, ROOM))
# Hall outer walls
walls.append(('hall_south_wall_left', -T, 5 * FT, -2 * T - H, -T - H, HALL))
walls.append(('hall_south_wall_right', 5 * FT + D, L + 2 * T + H, -2 * T - H, -T - H, HALL))
walls.append(('hall_east_wall', L + T + H, L + 2 * T + H, -2 * T - H, W + T, HALL))


def box(name, x0, x1, y0, y1, color):
    """Return the SDF text for one static box-shaped wall."""
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    sx, sy = x1 - x0, y1 - y0
    geo = f'<geometry><box><size>{sx:.4f} {sy:.4f} {HGT}</size></box></geometry>'
    return f"""    <model name='{name}'>
      <static>true</static>
      <pose>{cx:.4f} {cy:.4f} {HGT / 2} 0 0 0</pose>
      <link name='link'>
        <collision name='collision'>{geo}</collision>
        <visual name='visual'>{geo}
          <material><ambient>{color}</ambient><diffuse>{color}</diffuse></material>
        </visual>
      </link>
    </model>
"""


